const ATTRS_LUCIDE =
  'viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"'

/**
 * SVG inline listo para incrustar en el HTML del contenido.
 * `stroke="currentColor"` → el icono hereda el color del texto/tema (claro y oscuro).
 */
export function svgInline(nombre) {
  const cuerpo = LUCIDE[nombre]
  if (!cuerpo) throw new Error(`Icono desconocido: ${nombre}`)
  return `<svg xmlns="http://www.w3.org/2000/svg" ${ATTRS_LUCIDE} aria-hidden="true" focusable="false">${cuerpo}</svg>`
}

/** El mismo SVG como data-URI, para usarlo como `mask-image` en CSS. */
export function svgDataUri(nombre) {
  const cuerpo = LUCIDE[nombre]
  if (!cuerpo) throw new Error(`Icono desconocido: ${nombre}`)
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" ${ATTRS_LUCIDE}>${cuerpo}</svg>`
  // Solo se escapa lo que rompería un url("…") dentro de CSS. El resto se deja
  // legible a propósito (un data-URI 100% percent-encoded pesa bastante más).
  const escapado = svg
    .replace(/"/g, "'")
    .replace(/%/g, '%25')
    .replace(/#/g, '%23')
    .replace(/</g, '%3C')
    .replace(/>/g, '%3E')
    .replace(/\s+/g, ' ')
  return `data:image/svg+xml,${escapado}`
}
